import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { chromium } from 'playwright';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const out = path.join(root, 'artifacts', 'issue103');
await fs.mkdir(out, { recursive: true });
const browser = await chromium.launch({ headless: true });
const page = await browser.newPage({ viewport: { width: 1672, height: 941 }, deviceScaleFactor: 1 });
const errors = [];
page.on('pageerror', error => errors.push(error.stack || error.message));
await page.goto(`file://${path.join(root, 'gui-mockup', 'index.html').replaceAll('\\', '/')}`);
await page.waitForTimeout(350);

const result = await page.evaluate(async () => {
  const c = window.TimingChartProductionController;
  c.actions.selectObject({ dataset: { signal: 'req_valid', kind: 'signal' } });
  c.actions.setViewMode('split');
  c.actions.setBottomTab('annotation');
  c.actions.setFollowSelection(false);
  c.actions.setPinned(true);
  c.model.view.zoom = 1.5;
  c.model.view.scope = [];
  c.model.view.bottomHeight = 330;
  c.model.timeSelection = { cycle: 7, rangeStart: 3, rangeEnd: 7, source: 'acceptance' };
  c.model.editor.rowIndex = 1;
  const before = { selection: structuredClone(c.model.selection), view: structuredClone(c.model.view), time: structuredClone(c.model.timeSelection), editor: structuredClone(c.model.editor), value: c.model.document.signals.find(signal => signal.id === 'req_valid').values[1].value };
  const changed = c.actions.updateSignalValue('req_valid', 1, 'value', '0');
  const afterChange = { value: c.model.document.signals.find(signal => signal.id === 'req_valid').values[1].value, history: c.model.history.undo.length };
  const undone = c.actions.undo();
  await new Promise(resolve => setTimeout(resolve, 80));
  const afterUndo = { selection: structuredClone(c.model.selection), view: structuredClone(c.model.view), time: structuredClone(c.model.timeSelection), editor: structuredClone(c.model.editor), value: c.model.document.signals.find(signal => signal.id === 'req_valid').values[1].value };
  const redone = c.actions.redo();
  await new Promise(resolve => setTimeout(resolve, 80));
  const afterRedo = { selection: structuredClone(c.model.selection), view: structuredClone(c.model.view), time: structuredClone(c.model.timeSelection), editor: structuredClone(c.model.editor), value: c.model.document.signals.find(signal => signal.id === 'req_valid').values[1].value };
  return { before, changed, afterChange, undone, afterUndo, redone, afterRedo, renderedTab: document.querySelector('#bottomContent')?.dataset.renderedTab, activeTab: document.querySelector('#bottomTabs .btab.active')?.dataset.tab };
});

assert.equal(result.changed, true);
assert.equal(result.undone, true);
assert.equal(result.redone, true);
assert.equal(result.afterUndo.value, result.before.value);
assert.equal(result.afterRedo.value, 0);
assert.deepEqual(result.afterUndo.selection, result.before.selection);
assert.equal(result.afterUndo.view.mode, 'split');
assert.equal(result.afterUndo.view.tab, 'annotation');
assert.equal(result.afterUndo.view.followSelection, false);
assert.equal(result.afterUndo.view.pinned, true);
assert.equal(result.afterUndo.view.zoom, 1.5);
assert.deepEqual(result.afterUndo.time, result.before.time);
assert.equal(result.afterUndo.editor.rowIndex, result.before.editor.rowIndex);
assert.equal(result.renderedTab, 'annotation');
assert.equal(result.activeTab, 'annotation');
assert.equal(errors.length, 0, errors.join('\n'));
await page.screenshot({ path: path.join(out, 'issue103-1672x941.png') });
await browser.close();
const acceptance = { issue: 103, context: { selection: true, view: true, timeSelection: true, editor: true, followPin: true }, undoRedo: true, artifacts: ['issue103-1672x941.png'], errors, pass: true };
await fs.writeFile(path.join(out, 'acceptance.json'), `${JSON.stringify(acceptance, null, 2)}\n`);
console.log('Issue #103 acceptance passed: Undo/Redo preserves compatible selection and editing context.');
