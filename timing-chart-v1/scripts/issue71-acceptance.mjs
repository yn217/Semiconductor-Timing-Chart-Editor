import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { chromium } from 'playwright';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const out = path.join(root, 'artifacts', 'issue71');
await fs.mkdir(out, { recursive: true });
const browser = await chromium.launch({ headless: true });
const page = await browser.newPage({ viewport: { width: 1672, height: 941 }, deviceScaleFactor: 1 });
const errors = [];
page.on('pageerror', error => errors.push(error.stack || error.message));
await page.goto(`file://${path.join(root, 'gui-mockup', 'index.html').replaceAll('\\', '/')}`);
await page.waitForTimeout(350);

const result = await page.evaluate(async () => {
  const c = window.TimingChartProductionController;
  const normalize = value => String(value || '').replace(/[\s\n]+/g, '');
  const tool = label => [...document.querySelectorAll('#ribbonHome .tool')].find(node => normalize(node.querySelector('.tool-label')?.textContent) === normalize(label));
  const clickTool = async label => { const node = tool(label); if (!node) throw new Error(`missing Home tool ${label}`); if (node.disabled) throw new Error(`disabled Home tool ${label}: ${node.title}`); node.click(); await new Promise(resolve => setTimeout(resolve, 70)); return node; };
  const canonical = () => JSON.stringify(c.getSerializableDocument());
  const row = id => document.querySelector(`#groups .row[data-signal="${CSS.escape(id)}"]`);
  const cycleRow = id => document.querySelector(`#cycleCanvas .wave-row[data-signal="${CSS.escape(id)}"]`);
  const selectRow = async id => { row(id)?.click(); await new Promise(resolve => setTimeout(resolve, 45)); };
  const original = canonical();
  await selectRow('req_addr[7:0]');
  const beforeCopy = { document: canonical(), history: c.model.history.undo.length, dirty: c.model.persistence.dirty, wave: c.renderMetrics?.waveDromRenders || 0 };
  await clickTool('コピー');
  const afterCopy = { document: canonical(), history: c.model.history.undo.length, dirty: c.model.persistence.dirty, clipboard: c.model.clipboard?.kind, wave: c.renderMetrics?.waveDromRenders || 0 };
  await clickTool('貼付');
  const pastedId = c.model.selection.id;
  const pasted = { id: pastedId, historyDelta: c.model.history.undo.length - beforeCopy.history, group: c.model.document.signalGroups.find(group => group.rows.includes(pastedId))?.id, left: Boolean(row(pastedId)), cycle: Boolean(cycleRow(pastedId)), sameRole: c.model.document.signals.find(signal => signal.id === pastedId)?.role === 'input', sameSource: JSON.stringify(c.model.document.signals.find(signal => signal.id === pastedId)?.source) === JSON.stringify(c.model.document.signals.find(signal => signal.id === 'req_addr[7:0]')?.source) };
  const afterPaste = canonical();
  await clickTool('Undo');
  const undoPaste = { exact: canonical() === beforeCopy.document, removed: !row(pastedId) };
  await clickTool('Redo');
  const redoPaste = { restored: canonical() === afterPaste, left: Boolean(row(pastedId)) };
  await selectRow('req_addr[7:0]');
  const beforeDuplicateHistory = c.model.history.undo.length;
  await clickTool('複製');
  const duplicateId = c.model.selection.id;
  const duplicate = { id: duplicateId, immediatelyAfter: c.model.document.signalGroups.find(group => group.rows.includes('req_addr[7:0]'))?.rows.indexOf(duplicateId) === c.model.document.signalGroups.find(group => group.rows.includes('req_addr[7:0]'))?.rows.indexOf('req_addr[7:0]') + 1, historyDelta: c.model.history.undo.length - beforeDuplicateHistory, left: Boolean(row(duplicateId)), cycle: Boolean(cycleRow(duplicateId)) };
  await clickTool('削除');
  const deleted = { removed: !c.model.document.signals.some(signal => signal.id === duplicateId) && !row(duplicateId) };
  await selectRow('comment_01');
  const commentBefore = c.model.document.signals.find(signal => signal.id === 'comment_01');
  await clickTool('複製');
  const commentCopyId = c.model.selection.id;
  const commentDuplicate = { kind: c.model.selection.kind, titlePreserved: c.model.document.signals.find(signal => signal.id === commentCopyId)?.title === commentBefore.title, bodyPreserved: c.model.document.signals.find(signal => signal.id === commentCopyId)?.body === commentBefore.body, groupPreserved: c.model.document.signalGroups.find(group => group.rows.includes(commentCopyId))?.id === 'group_input', cycle: Boolean(cycleRow(commentCopyId)) };
  await clickTool('切取');
  const commentCut = { clipboard: c.model.clipboard?.kind, removed: !c.model.document.signals.some(signal => signal.id === commentCopyId) };
  await clickTool('貼付');
  const commentPasteId = c.model.selection.id;
  const commentPaste = { restored: c.model.document.signals.some(signal => signal.id === commentPasteId), titlePreserved: c.model.document.signals.find(signal => signal.id === commentPasteId)?.title === commentBefore.title, bodyPreserved: c.model.document.signals.find(signal => signal.id === commentPasteId)?.body === commentBefore.body, cycle: Boolean(cycleRow(commentPasteId)) };
  await selectRow('req_valid');
  document.dispatchEvent(new KeyboardEvent('keydown', { key: 'c', ctrlKey: true, bubbles: true }));
  const keyboardCopy = { clipboard: c.model.clipboard?.kind, unchanged: canonical() === canonical() };
  c.actions.selectAnnotation('ann_default_range');
  await new Promise(resolve => setTimeout(resolve, 40));
  const beforeAnnotation = c.model.document.annotations.length;
  await clickTool('複製');
  const annotationCopy = c.model.document.annotations.at(-1);
  const annotation = { countIncreased: c.model.document.annotations.length === beforeAnnotation + 1, newId: annotationCopy?.id !== 'ann_default_range', anchors: Boolean(annotationCopy?.start?.signal && annotationCopy?.end?.signal), noAbsoluteGeometry: !('canvasX' in (annotationCopy || {})) && !('canvasY' in (annotationCopy || {})) };
  const saved = c.prepareSaveText();
  const savedCanonical = JSON.stringify(JSON.parse(saved.text));
  const roundTrip = await c.actions.openText(saved.text, { fileName: 'issue71-roundtrip.tcd', unsavedDecision: 'discard' });
  const roundTripExact = roundTrip && canonical() === savedCanonical;
  c.model.selection = { kind: 'none', id: null }; c.render();
  const noSelection = Object.fromEntries([...document.querySelectorAll('#ribbonHome .tool[data-edit-command]')].map(button => [button.dataset.editCommand, { disabled: button.disabled, title: Boolean(button.title) }]));
  return { original, beforeCopy, afterCopy, pasted, undoPaste, redoPaste, duplicate, deleted, commentDuplicate, commentCut, commentPaste, keyboardCopy, annotationCopy: annotation, roundTripExact, noSelection, finalDirty: c.model.persistence.dirty, errors: [] };
});

assert.equal(result.afterCopy.document, result.beforeCopy.document);
assert.equal(result.afterCopy.history, result.beforeCopy.history);
assert.equal(result.afterCopy.dirty, result.beforeCopy.dirty);
assert.equal(result.afterCopy.clipboard, 'signal');
assert.equal(result.afterCopy.wave, result.beforeCopy.wave);
assert.equal(result.pasted.historyDelta, 1);
assert.equal(result.pasted.group, 'group_input');
assert.equal(result.pasted.left, true);
assert.equal(result.pasted.cycle, true);
assert.equal(result.pasted.sameRole, true);
assert.equal(result.pasted.sameSource, true);
assert.equal(result.undoPaste.exact, true);
assert.equal(result.undoPaste.removed, true);
assert.equal(result.redoPaste.restored, true);
assert.equal(result.duplicate.immediatelyAfter, true);
assert.equal(result.duplicate.historyDelta, 1);
assert.equal(result.duplicate.left, true);
assert.equal(result.duplicate.cycle, true);
assert.equal(result.deleted.removed, true);
assert.equal(result.commentDuplicate.kind, 'comment');
assert.equal(result.commentDuplicate.titlePreserved, true);
assert.equal(result.commentDuplicate.groupPreserved, true);
assert.equal(result.commentDuplicate.bodyPreserved, true);
assert.equal(result.commentDuplicate.cycle, true);
assert.equal(result.commentCut.clipboard, 'comment');
assert.equal(result.commentCut.removed, true);
assert.equal(result.commentPaste.restored, true);
assert.equal(result.commentPaste.titlePreserved, true);
assert.equal(result.commentPaste.bodyPreserved, true);
assert.equal(result.commentPaste.cycle, true);
assert.equal(result.keyboardCopy.clipboard, 'signal');
assert.equal(result.annotationCopy.countIncreased, true);
assert.equal(result.annotationCopy.newId, true);
assert.equal(result.annotationCopy.anchors, true);
assert.equal(result.annotationCopy.noAbsoluteGeometry, true);
assert.equal(result.roundTripExact, true);
assert.equal(result.noSelection.copy.disabled, true);
assert.equal(result.noSelection.cut.disabled, true);
assert.equal(result.noSelection.delete.disabled, true);
assert.equal(result.noSelection.duplicate.disabled, true);
assert.equal(result.noSelection.paste.disabled, false);
assert.equal(errors.length, 0, errors.join('\n'));
await page.screenshot({ path: path.join(out, 'issue71-1672x941.png') });
await browser.close();
await fs.writeFile(path.join(out, 'acceptance.json'), `${JSON.stringify({ issue: 71, result, pass: true }, null, 2)}\n`);
console.log('Issue #71 acceptance passed: canonical Home edit commands, structured clipboard, undo/redo, signal/comment/annotation effects, and keyboard copy.');
