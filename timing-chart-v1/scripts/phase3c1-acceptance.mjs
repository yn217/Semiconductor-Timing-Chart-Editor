import assert from 'node:assert/strict';
import crypto from 'node:crypto';
import fs from 'node:fs';
import { spawn } from 'node:child_process';
import { chromium } from 'playwright';

const root = 'artifacts/gui-phase3c1';
fs.mkdirSync(root, { recursive: true });
const hash = file => crypto.createHash('sha256').update(fs.readFileSync(file)).digest('hex');
assert.equal(hash('gui-mockup/styles.css'), hash('references/gui-replacement-pack/production/styles.css'));
assert.equal(hash('gui-mockup/icons.svg'), hash('references/gui-replacement-pack/production/icons.svg'));
const server = spawn('python', ['-m', 'http.server', '4185'], { cwd: process.cwd(), stdio: 'ignore' });
const wait = ms => new Promise(resolve => setTimeout(resolve, ms));
const report = { schema: {}, roundTrip: {}, transient: {}, clock: {}, pass: false };
try {
  await wait(700);
  const browser = await chromium.launch({ headless: true });
  const page = await browser.newPage({ viewport: { width: 1672, height: 941 }, deviceScaleFactor: 1 });
  await page.goto('http://127.0.0.1:4185/gui-mockup/', { waitUntil: 'networkidle' });
  const canonical = await page.evaluate(() => window.TimingChartProductionController.getSerializableDocument());
  const issues = await page.evaluate(documentValue => window.TimingChartProductionController.validateDocument(documentValue), canonical);
  assert.deepEqual(issues, []);
  report.schema = { formatVersion: canonical.formatVersion, requiredFields: ['document', 'timeline', 'signalGroups', 'signals', 'annotations', 'legend', 'layout', 'transactions', 'constraints'], issues, pass: true };
  const json = JSON.stringify(canonical);
  const roundTrip = JSON.parse(json);
  const roundTripIssues = await page.evaluate(documentValue => window.TimingChartProductionController.validateDocument(documentValue), roundTrip);
  assert.deepEqual(roundTripIssues, []);
  assert.deepEqual(roundTrip, canonical);
  report.roundTrip = { semanticEqual: true, issues: roundTripIssues, pass: true };
  for (const field of ['selection', 'editor', 'validation', 'view', 'waveGeometry']) assert.equal(Object.hasOwn(canonical, field), false);
  assert.equal(/WaveJSON|waveJson|wave\s*:\s*['"]/.test(json), false);
  assert.equal(/"at"\s*:/.test(json), false);
  assert.equal(canonical.signals.some(signal => (signal.values || []).some(value => Object.hasOwn(value, 'duration') || Object.hasOwn(value, 'end'))), false);
  report.transient = { excluded: ['selection', 'editor', 'validation', 'view', 'waveGeometry'], waveJsonExcluded: true, atExcluded: true, derivedFieldsExcluded: true, pass: true };
  const clock = canonical.signals.find(signal => signal.id === 'clk');
  assert.deepEqual(Object.keys(clock.generator).sort(), ['duty', 'initial', 'period', 'phase', 'polarity', 'start'].sort());
  assert.equal(clock.generator.duty, 0.5);
  assert.equal(clock.edgeCounter.countFrom, 'signal-start');
  assert.equal(canonical.timeline.referenceClock, 'clk');
  const before = await page.evaluate(() => window.TimingChartProductionController.model.waveGeometry.signals.clk.risingEdge.map(edge => edge.canvasX));
  await page.locator('.row[data-signal="clk"]').click();
  await page.locator('[data-clock-field="period"]').fill('2');
  await page.locator('[data-clock-field="period"]').dispatchEvent('change');
  await wait(60);
  const after = await page.evaluate(() => ({ document: window.TimingChartProductionController.getSerializableDocument(), geometry: window.TimingChartProductionController.model.waveGeometry.signals.clk.risingEdge.map(edge => edge.canvasX), wave: window.TimingWaveDromAdapter.waveFor(window.TimingChartProductionController.selectors.getSignal('clk'), 10) }));
  assert.equal(after.document.signals.find(signal => signal.id === 'clk').generator.period, 2);
  assert.equal(after.wave.period, 2);
  assert.notDeepEqual(after.geometry, before);
  report.clock.periodEdit = { canonicalPeriod: 2, waveDromPeriod: after.wave.period, geometryChanged: true };
  await page.locator('[data-clock-field="duty"]').fill('50');
  await page.locator('[data-clock-field="duty"]').dispatchEvent('change');
  await wait(30);
  assert.equal((await page.evaluate(() => window.TimingChartProductionController.getSerializableDocument())).signals.find(signal => signal.id === 'clk').generator.duty, 0.5);
  report.clock.duty = { uiPercent: 50, canonical: 0.5, pass: true };
  fs.writeFileSync(`${root}/canonical-document.json`, `${JSON.stringify(canonical, null, 2)}\n`);
  fs.writeFileSync(`${root}/roundtrip-document.json`, `${JSON.stringify(roundTrip, null, 2)}\n`);
  fs.writeFileSync(`${root}/schema-validation.json`, `${JSON.stringify({ issues, roundTripIssues }, null, 2)}\n`);
  report.pass = true;
  fs.writeFileSync(`${root}/acceptance.json`, `${JSON.stringify(report, null, 2)}\n`);
  await browser.close();
  console.log('Phase 3C.1 acceptance passed: canonical schema, transient boundary, round trip, clock generator, and duty conversion.');
} finally { server.kill(); if (!report.pass) fs.writeFileSync(`${root}/acceptance.json`, `${JSON.stringify(report, null, 2)}\n`); }
