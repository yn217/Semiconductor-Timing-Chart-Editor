import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { chromium } from 'playwright';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const out = path.join(root, 'artifacts', 'issue48');
await fs.mkdir(out, { recursive: true });
const browser = await chromium.launch({ headless: true });
const page = await browser.newPage({ viewport: { width: 1672, height: 941 }, deviceScaleFactor: 1 });
const errors = [];
page.on('pageerror', error => errors.push(error.stack || error.message));
await page.goto(`file://${path.join(root, 'gui-mockup', 'index.html').replaceAll('\\', '/')}`);
await page.waitForTimeout(350);

const result = await page.evaluate(async () => {
  const c = window.TimingChartProductionController;
  const rows = group => [...document.querySelectorAll(`#groups .group[data-group-id="${group.id}"] .row`)].map(row => row.dataset.signal || row.dataset.commentId);
  const tool = text => [...document.querySelectorAll('#ribbonHome .tool')].find(node => (node.querySelector('.tool-label')?.textContent || node.textContent).replace(/\s/g, '').includes(text));
  const group = c.model.document.signalGroups[0];
  const original = [...group.rows];
  const select = id => document.querySelector(`#groups .row[data-signal="${CSS.escape(id)}"]`)?.click();
  select(original[1]);
  const up = tool('上へ'); const down = tool('下へ');
  const historyBefore = c.model.history.undo.length;
  up.click();
  const afterUp = { rows: [...group.rows], dom: rows(group), selection: c.model.selection.id, history: c.model.history.undo.length, upDisabled: up.disabled, downDisabled: down.disabled };
  down.click();
  const afterDown = { rows: [...group.rows], dom: rows(group), selection: c.model.selection.id, history: c.model.history.undo.length };
  const undo = c.actions.undo();
  const afterUndo = [...c.model.document.signalGroups[0].rows];
  const redo = c.actions.redo();
  const afterRedo = [...c.model.document.signalGroups[0].rows];
  const comment = c.model.document.signals.find(signal => signal.type === 'commentRow');
  select(comment.id);
  const commentUp = tool('上へ'); commentUp.click();
  const currentGroup = () => c.model.document.signalGroups.find(item => (item.rows || []).includes(comment.id));
  const afterCommentUp = [...currentGroup().rows];
  tool('下へ').click();
  const boundaryFirst = async () => { const current = currentGroup(); select(current.rows[0]); await new Promise(resolve => requestAnimationFrame(resolve)); return { up: tool('上へ').disabled, title: tool('上へ').title }; };
  const boundaryLast = async () => { const current = currentGroup(); select(current.rows[current.rows.length - 1]); await new Promise(resolve => requestAnimationFrame(resolve)); return { down: tool('下へ').disabled, title: tool('下へ').title }; };
  return { original, historyBefore, afterUp, afterDown, undo, afterUndo, redo, afterRedo, commentId: comment.id, afterCommentUp, boundaryFirst: await boundaryFirst(), boundaryLast: await boundaryLast(), errors: [] };
});

assert.deepEqual(result.afterUp.rows.slice(0, 2), [result.original[1], result.original[0]]);
assert.deepEqual(result.afterUp.rows, result.afterUp.dom);
assert.equal(result.afterUp.selection, result.original[1]);
assert.equal(result.afterUp.history, result.historyBefore + 1);
assert.deepEqual(result.afterDown.rows, result.original);
assert.deepEqual(result.afterDown.rows, result.afterDown.dom);
assert.equal(result.afterDown.history, result.historyBefore + 2);
assert.equal(result.undo, true);
assert.deepEqual(result.afterUndo, [result.original[1], result.original[0], ...result.original.slice(2)]);
assert.equal(result.redo, true);
assert.deepEqual(result.afterRedo, result.original);
assert.notDeepEqual(result.afterCommentUp, result.original);
assert.equal(result.boundaryFirst.up, true, JSON.stringify(result));
assert.match(result.boundaryFirst.title, /先頭/);
assert.equal(result.boundaryLast.down, true);
assert.match(result.boundaryLast.title, /末尾/);
assert.equal(errors.length, 0, errors.join('\n'));
await page.screenshot({ path: path.join(out, 'issue48-1672x941.png') });
await fs.writeFile(path.join(out, 'acceptance.json'), `${JSON.stringify({ issue: 48, result, pass: true }, null, 2)}\n`);
await browser.close();
console.log('Issue #48 acceptance passed: Home reorder, comment reorder, group boundaries, selection, and Undo/Redo.');
