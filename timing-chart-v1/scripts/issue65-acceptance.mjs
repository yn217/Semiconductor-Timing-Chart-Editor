import assert from 'node:assert/strict';
import fs from 'node:fs';
import { spawn } from 'node:child_process';
import { chromium } from 'playwright';

const root = 'artifacts/issue65';
fs.mkdirSync(root, { recursive: true });
const server = spawn('python', ['-m', 'http.server', '4243'], { stdio: 'ignore' });
const pause = ms => new Promise(resolve => setTimeout(resolve, ms));
try {
  await pause(400);
  const browser = await chromium.launch({ headless: true });
  const page = await browser.newPage({ viewport: { width: 1672, height: 941 }, deviceScaleFactor: 1 });
  await page.goto('http://127.0.0.1:4243/gui-mockup/', { waitUntil: 'networkidle' });
  const result = await page.evaluate(async () => {
    const c = window.TimingChartProductionController;
    const wait = ms => new Promise(resolve => setTimeout(resolve, ms));
    const selectTab = async tab => { document.querySelector(`#bottomTabs [data-tab="${tab}"]`).click(); await wait(25); };
    const doc = () => c.getSerializableDocument();

    document.querySelector('.row[data-signal="req_valid"]').click(); await wait(35);
    const value = document.querySelector('#bottomContent [data-editor-field="value"][data-editor-index="1"]');
    if (!value) throw new Error('Signal editor value field missing');
    const beforeValue = doc().signals.find(signal => signal.id === 'req_valid').values[1].value;
    value.value = '0'; value.dispatchEvent(new Event('change', { bubbles: true })); await wait(30);
    if (doc().signals.find(signal => signal.id === 'req_valid').values[1].value === beforeValue) throw new Error('Signal value edit did not reach canonical model');
    if (!c.model.history.undo.length || !c.model.persistence.dirty) throw new Error('Signal edit did not create history/dirty state');

    c.actions.addCommentRow({ id: 'issue65_comment', title: 'Issue 65', body: 'initial' }); await wait(25);
    await selectTab('signal');
    const title = document.querySelector('[data-comment-field="title"]');
    if (!title) throw new Error('Comment editor missing');
    title.value = 'Updated comment'; title.dispatchEvent(new Event('change', { bubbles: true })); await wait(20);
    if (c.selectors.getComments().find(comment => comment.id === 'issue65_comment').title !== 'Updated comment') throw new Error('Comment edit did not reach canonical model');
    const duplicateButton = document.querySelector('[data-comment-action="duplicate"]');
    if (duplicateButton.disabled) throw new Error(`Comment duplicate button disabled: ${duplicateButton.title}`);
    duplicateButton.click(); await wait(25);
    const duplicateId = c.model.selection.id;
    if (!c.selectors.getComments().some(comment => comment.id === duplicateId)) throw new Error('Comment duplicate did not create a canonical row');
    const deleteButton = document.querySelector('[data-comment-action="delete"]');
    if (deleteButton.disabled) throw new Error(`Comment delete button disabled: ${deleteButton.title}`);
    deleteButton.click(); await wait(25);
    if (c.selectors.getComments().some(comment => comment.id === duplicateId)) throw new Error(`Comment delete did not remove canonical row: selection=${JSON.stringify(c.model.selection)} buttons=${document.querySelectorAll('[data-comment-action]').length}`);

    await selectTab('annotation');
    const annotationRow = document.querySelector('#bottomContent tr[data-annotation-id]');
    annotationRow.click(); await wait(25);
    const label = annotationRow.querySelector('[data-annotation-field="label"]');
    const color = annotationRow.querySelector('[data-annotation-field="color"]');
    const typeSelect = annotationRow.querySelector('[data-annotation-field="type"]');
    if (!label || !color || !typeSelect) throw new Error('Annotation table editor fields missing');
    label.value = 'Edited annotation'; label.dispatchEvent(new Event('change', { bubbles: true }));
    color.value = '#e39a25'; color.dispatchEvent(new Event('change', { bubbles: true })); await wait(25);
    // Per #118/#124 architecture, anchor pick and per-anchor cycle editing now live in the Inspector, not the Bottom table.
    c.actions.selectAnnotation(c.model.selection.id); await wait(50);
    const pickButton = document.querySelector('#inspectorBody [data-inspector-anchor-pick]');
    if (!pickButton) throw new Error('Inspector anchor pick entry point missing');
    pickButton.click(); await wait(20);
    if (!document.querySelector('#cycleCanvas')?.dataset.annotationAnchorPick) throw new Error('Annotation anchor picker was not activated');
    c.actions.cancelAnnotationAnchorSelection();
    const endCycleInput = document.querySelector('#inspectorBody [data-annotation-anchor-key="end"][data-annotation-anchor-prop="cycle"]');
    if (!endCycleInput) throw new Error('Inspector End Anchor cycle field missing');
    const endCycleBefore = Number(endCycleInput.value); const cycleLimit = Number(c.model.document.timeline.cycleCount); const endCycleTarget = endCycleBefore < cycleLimit ? endCycleBefore + 1 : Math.max(0, endCycleBefore - 1); endCycleInput.value = String(endCycleTarget); endCycleInput.dispatchEvent(new Event('change', { bubbles: true })); await wait(25);
    const typeAfterEdit = document.querySelector('#bottomContent tr[data-annotation-id] [data-annotation-field="type"]');
    const originalType = typeAfterEdit.value; typeAfterEdit.value = originalType === 'range' ? 'bracket' : 'range'; typeAfterEdit.dispatchEvent(new Event('change', { bubbles: true })); await wait(25);
    const typeRestore = document.querySelector('#bottomContent tr[data-annotation-id] [data-annotation-field="type"]'); typeRestore.value = originalType; typeRestore.dispatchEvent(new Event('change', { bubbles: true })); await wait(25);
    const selectedAnnotation = c.model.document.annotations.find(item => item.id === c.model.selection.id);
    if (selectedAnnotation.label !== 'Edited annotation' || selectedAnnotation.color !== '#e39a25' || selectedAnnotation.type !== originalType || Number(selectedAnnotation.end?.cycle) !== endCycleTarget) throw new Error('Annotation table/Inspector edit did not reach canonical model');

    await selectTab('transaction');
    c.actions.addTransaction({ id: 'issue65_txn', name: 'Initial', start: 1, end: 3 }); await wait(25);
    const transactionName = document.querySelector('[data-transaction-field="name"]');
    if (!transactionName) throw new Error('Transaction editor field missing');
    transactionName.value = 'Updated transaction'; transactionName.dispatchEvent(new Event('change', { bubbles: true })); await wait(25);
    const linkedSignals = document.querySelector('[data-transaction-field="linkedSignals"]');
    const phases = document.querySelector('[data-transaction-field="phases"]');
    if (!linkedSignals || !phases) throw new Error('Transaction linked-signal/phase editors missing');
    linkedSignals.options[0].selected = true; linkedSignals.dispatchEvent(new Event('change', { bubbles: true }));
    phases.value = JSON.stringify([{ name: 'Setup', start: 1, end: 2 }]); phases.dispatchEvent(new Event('change', { bubbles: true })); await wait(25);
    const transaction = c.model.document.transactions.find(item => item.id === 'issue65_txn');
    if (transaction.name !== 'Updated transaction' || !transaction.linkedSignals?.length || transaction.phases?.[0]?.name !== 'Setup') throw new Error('Transaction linked-signal/phase edit did not reach canonical model');

    await selectTab('json');
    document.querySelector('[data-json-action="export"]').click(); await wait(25);
    if (!window.TimingChartLastJsonExport?.includes('issue65_txn')) throw new Error('JSON export did not contain current canonical document');
    return { signalEdit: true, commentEditDuplicateDelete: true, annotationTableEdit: true, transactionEdit: true, jsonExport: true, pass: true };
  });
  await page.locator('.seg[data-mode="cycle"]').click();
  await page.waitForTimeout(35);
  await page.locator('.row[data-signal="req_valid"]').click();
  await page.waitForTimeout(35);
  await page.locator('#bottomTabs [data-tab="signal"]').click();
  await page.waitForTimeout(35);
  await page.locator('#bottomContent [data-editor-action="export"]').click();
  const signalExport = await page.evaluate(() => window.TimingChartLastSignalExport);
  const signalPayload = JSON.parse(signalExport); signalPayload.signal.values[0].value = signalPayload.signal.type === 'binary' ? 1 : signalPayload.signal.values[0].value;
  const signalChooser = page.waitForEvent('filechooser');
  await page.locator('#bottomContent [data-editor-action="import"]').click();
  await (await signalChooser).setFiles({ name: 'req_valid.signal.json', mimeType: 'application/json', buffer: Buffer.from(JSON.stringify(signalPayload)) });
  await page.waitForTimeout(35);
  assert.equal(await page.evaluate(() => window.TimingChartProductionController.model.document.signals.find(signal => signal.id === 'req_valid').values[0].value), 1);
  await page.locator('.row[data-signal="clk"]').click();
  await page.waitForTimeout(35);
  await page.locator('.seg[data-mode="cycle"]').click();
  await page.waitForTimeout(35);
  await page.locator('#bottomTabs [data-tab="signal"]').click();
  await page.waitForTimeout(35);
  await page.locator('#bottomContent [data-clock-action="export"]').click();
  const clockExport = await page.evaluate(() => window.TimingChartLastClockExport);
  assert.match(clockExport, /generator/);
  const chooser = page.waitForEvent('filechooser');
  await page.locator('#bottomContent [data-clock-action="import"]').click();
  await (await chooser).setFiles({ name: 'clk.clock.json', mimeType: 'application/json', buffer: Buffer.from(clockExport) });
  await page.waitForTimeout(35);
  assert.ok(await page.evaluate(() => Boolean(window.TimingChartProductionController.getClockConfig('clk'))));
  await page.locator('#bottomTabs [data-tab="json"]').click();
  await page.waitForTimeout(35);
  const importedText = await page.evaluate(() => { const documentValue = structuredClone(window.TimingChartProductionController.getSerializableDocument()); documentValue.document.title = 'Issue65 imported through UI'; return JSON.stringify(documentValue); });
  const jsonChooser = page.waitForEvent('filechooser');
  await page.locator('#bottomContent [data-json-action="import"]').click();
  await (await jsonChooser).setFiles({ name: 'issue65-imported.tcd.json', mimeType: 'application/json', buffer: Buffer.from(importedText) });
  await page.waitForTimeout(45);
  assert.equal(await page.evaluate(() => window.TimingChartProductionController.model.document.document.title), 'Issue65 imported through UI');
  const sampleDir = '../timing-chart-v2/samples/golden-protocol/timing_chart_sample_pack/samples';
  const matrixFiles = ['01_apb_register_access.tcd.json', '02_ahb_lite_pipelined_transfer.tcd.json', '03_axi4_full_write_burst.tcd.json', '08_async_fifo_cdc.tcd.json'];
  const matrixResults = [];
  for (const file of matrixFiles) {
    const sampleText = fs.readFileSync(`${sampleDir}/${file}`, 'utf8');
    assert.equal(await page.evaluate(async text => window.TimingChartProductionController.actions.openText(text, { fileName: text.slice(0, 0) + 'matrix.tcd.json', unsavedDecision: 'discard' }), sampleText), true, `${file}: open failed`);
    await page.waitForTimeout(45);
    await page.locator('.seg[data-mode="cycle"]').click();
    await page.waitForTimeout(25);
    const targetSignalId = await page.evaluate(() => { const signals = window.TimingChartProductionController.model.document.signals || []; return signals.find(signal => signal.type !== 'commentRow' && Array.isArray(signal.values) && signal.values.length)?.id || signals.find(signal => signal.type !== 'commentRow')?.id; });
    assert.ok(targetSignalId, `${file}: canonical signal missing`);
    const signalRow = page.locator(`#leftPanel .row[data-signal="${targetSignalId}"]`).last();
    assert.ok(await signalRow.count(), `${file}: editable signal row missing`);
    await signalRow.click();
    await page.waitForTimeout(30);
    await page.locator('#bottomTabs [data-tab="signal"]').click({ force: true });
    await page.waitForTimeout(80);
    if (!await page.locator('#bottomContent [data-editor-field]').count()) { const debug = await page.evaluate(() => ({ selection: window.TimingChartProductionController.model.selection, tab: window.TimingChartProductionController.model.view.tab, rendered: document.querySelector('#bottomContent')?.dataset.renderedTab, text: document.querySelector('#bottomContent')?.textContent?.slice(0, 240) })); throw new Error(`${file}: Signal editor missing ${JSON.stringify(debug)}`); }
    await page.locator('#bottomTabs [data-tab="annotation"]').click();
    await page.waitForTimeout(25);
    const annotationCount = await page.locator('#bottomContent tr[data-annotation-id]').count();
    await page.locator('#bottomTabs [data-tab="json"]').click();
    await page.waitForTimeout(25);
    const snapshot = await page.evaluate(() => { const c = window.TimingChartProductionController; return { signals: c.model.document.signals.length, annotations: c.model.document.annotations.length, transactions: c.model.document.transactions.length, json: document.querySelector('#bottomContent')?.textContent || '' }; });
    assert.match(snapshot.json, new RegExp(`signals \\[${snapshot.signals}\\]`), `${file}: JSON model count mismatch`);
    matrixResults.push({ file, signalCount: snapshot.signals, annotationCount: snapshot.annotations, transactionCount: snapshot.transactions, annotationRows: annotationCount, pass: true });
  }
  await page.screenshot({ path: `${root}/issue65-1672x941.png` });
  await browser.close();
  const report = { issue: 65, ...result, signalImportExport: true, clockImportExport: true, jsonFileImport: true, matrixResults, pass: result.pass && matrixResults.every(item => item.pass), knownIncomplete: [] };
  fs.writeFileSync(`${root}/acceptance.json`, `${JSON.stringify(report, null, 2)}\n`);
  assert.ok(report.pass, 'Issue #65 progress acceptance failed');
  console.log('Issue #65 progress acceptance passed: Signal, Comment, Annotation, Transaction, and JSON editor paths use observable canonical operations.');
} finally { server.kill(); }
