import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { chromium } from 'playwright';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const out = path.join(root, 'artifacts', 'issue109');
await fs.mkdir(out, { recursive: true });
const browser = await chromium.launch({ headless: true });
const page = await browser.newPage({ viewport: { width: 1672, height: 941 }, deviceScaleFactor: 1 });
const errors = [];
page.on('pageerror', error => errors.push(error.stack || error.message));
await page.goto(`file://${path.join(root, 'gui-mockup', 'index.html').replaceAll('\\', '/')}`);
await page.waitForTimeout(450);

const result = await page.evaluate(async () => {
  const c = window.TimingChartProductionController;
  const initial = structuredClone(c.getSerializableDocument());
  c.actions.selectTimeRange(1, 3);
  const created = c.actions.addTimeGroup({ name: 'Read #1', category: 'Read', comment: 'First read' });
  const id = c.model.document.timeGroups[0]?.id;
  const list = c.selectors.getTimeGroups();
  const panelVisible = Boolean(document.querySelector('[data-time-groups-panel]'));
  const edited = c.actions.updateTimeGroup(id, 'name', 'Read retry') && c.actions.updateTimeGroup(id, 'comment', 'Updated') && c.actions.updateTimeGroup(id, 'category', 'Read');
  const collapsed = c.actions.setTimeGroupCollapsed(id, true);
  const collapsedState = c.model.document.timeGroups[0]?.presentation?.collapsed;
  const historyAfterCollapse = c.model.history.undo.length;
  const undoCollapse = c.actions.undo();
  const undoState = c.model.document.timeGroups[0]?.presentation?.collapsed;
  const redoCollapse = c.actions.redo();
  const redoState = c.model.document.timeGroups[0]?.presentation?.collapsed;
  const adjacent = c.actions.addTimeGroup({ start: 3, end: 4, name: 'Write #1', category: 'Write' });
  c.actions.selectTimeRange(2, 4);
  const partialRejected = c.actions.addTimeGroup({ name: 'Invalid overlap' }) === false;
  const saved = c.prepareSaveText();
  const opened = await c.actions.openText(saved.text, { fileName: 'issue109-roundtrip.tcd', unsavedDecision: 'discard' });
  const roundTrip = structuredClone(c.model.document.timeGroups);
  const beforeInsert = c.model.document.timeGroups.map(group => ({ id: group.id, start: group.start, end: group.end }));
  const inserted = c.actions.insertCycles(1, 2);
  const afterInsert = c.model.document.timeGroups.map(group => ({ id: group.id, start: group.start, end: group.end }));
  const dirtyBeforeReveal = c.model.persistence.dirty;
  const historyBeforeReveal = c.model.history.undo.length;
  const revealed = c.actions.revealTimeGroup(beforeInsert[0].id);
  const revealState = { range: [c.model.timeSelection.rangeStart, c.model.timeSelection.rangeEnd], dirty: c.model.persistence.dirty, history: c.model.history.undo.length };
  const wholeDeleteRejected = c.actions.deleteRange(1, 5) === false;
  const validation = c.getProblems(c.model.document);
  return { initial, created, id, list, panelVisible, edited, collapsed, collapsedState, historyAfterCollapse, undoCollapse, undoState, redoCollapse, redoState, adjacent, partialRejected, opened, roundTrip, beforeInsert, inserted, afterInsert, revealed, revealState, dirtyBeforeReveal, historyBeforeReveal, wholeDeleteRejected, validation, renderedTab: document.querySelector('#bottomContent')?.dataset.renderedTab };
});

assert.equal(result.created, true);
assert.equal(result.list[0].duration, 2);
assert.equal(result.list[0].state, 'Expanded');
assert.equal(result.panelVisible, true);
assert.equal(result.edited, true);
assert.equal(result.collapsed, true);
assert.equal(result.collapsedState, true);
assert.equal(result.undoCollapse, true);
assert.equal(result.undoState, undefined);
assert.equal(result.redoCollapse, true);
assert.equal(result.redoState, true);
assert.equal(result.adjacent, true);
assert.equal(result.partialRejected, true);
assert.equal(result.opened, true);
assert.ok(result.roundTrip.some(group => group.name === 'Read retry' && group.comment === 'Updated' && group.presentation?.collapsed === true));
result.beforeInsert.forEach((group, index) => { assert.equal(result.afterInsert[index].start, group.start + 2); assert.equal(result.afterInsert[index].end, group.end + 2); });
assert.equal(result.revealed, true);
assert.deepEqual(result.revealState.range, [result.afterInsert[0].start, result.afterInsert[0].end]);
assert.equal(result.revealState.dirty, result.dirtyBeforeReveal);
assert.equal(result.revealState.history, result.historyBeforeReveal);
assert.equal(result.wholeDeleteRejected, true);
assert.equal(result.validation.length, 0);
assert.equal(errors.length, 0);
await page.screenshot({ path: path.join(out, 'issue109-1672x941.png') });
await browser.close();
const acceptance = { issue: 109, rangeCreate: true, list: true, directEdit: true, collapseUndoRedo: true, overlapPolicy: true, saveOpen: true, insertTransform: true, revealViewOnly: true, explicitDeleteGuard: true, browserErrors: errors, result, artifacts: ['issue109-1672x941.png'], pass: true };
await fs.writeFile(path.join(out, 'acceptance.json'), `${JSON.stringify(acceptance, null, 2)}\n`);
console.log('Issue #109 acceptance passed: Time Group lifecycle, list metadata, collapse state, persistence, and timeline transforms.');
