import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { chromium } from 'playwright';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const out = path.join(root, 'artifacts', 'issue101');
await fs.mkdir(out, { recursive: true });
const browser = await chromium.launch({ headless: true });
const page = await browser.newPage({ viewport: { width: 1672, height: 941 }, deviceScaleFactor: 1 });
const errors = [];
page.on('pageerror', error => errors.push(error.stack || error.message));
await page.goto(`file://${path.join(root, 'gui-mockup', 'index.html').replaceAll('\\', '/')}`);
await page.waitForTimeout(350);

const parser = value => page.evaluate(({ value }) => window.TimingChartProductionController.parseSignalLiteral(value, { type: 'bus', width: 8, displayFormat: 'hex' }), { value });
assert.deepEqual(await parser('9A'), { valid: true, kind: 'hex', numericValue: '154', requiredBits: 8, containsUnknown: false, normalizedText: '9A', base: 16, width: 8, overflow: false, error: null });
assert.equal((await parser('0x9A')).valid, true);
assert.equal((await parser('1FF')).valid, false);
assert.equal((await parser('0x1FF')).valid, false);
assert.equal((await page.evaluate(() => window.TimingChartProductionController.parseSignalLiteral('1F', { type: 'bus', width: 5, displayFormat: 'hex' }).requiredBits)), 5);
assert.equal((await page.evaluate(() => window.TimingChartProductionController.parseSignalLiteral('20', { type: 'bus', width: 5, displayFormat: 'hex' }).valid)), false);
assert.equal((await page.evaluate(() => window.TimingChartProductionController.parseSignalLiteral('0000009A', { type: 'bus', width: 8, displayFormat: 'hex' }).valid)), true);
assert.equal((await page.evaluate(() => window.TimingChartProductionController.parseSignalLiteral('XX', { type: 'bus', width: 8, displayFormat: 'hex' }).valid)), true);
assert.equal((await page.evaluate(() => window.TimingChartProductionController.parseSignalLiteral('IDLE', { type: 'bus', width: 2, displayFormat: 'hex' }).kind)), 'symbolic');
assert.equal((await page.evaluate(() => window.TimingChartProductionController.parseSignalLiteral('0x1G', { type: 'bus', width: 8, displayFormat: 'hex' }).valid)), false);

const result = await page.evaluate(async () => {
  const c = window.TimingChartProductionController;
  const id = 'arbitrary_bus_101';
  if (c.selectors.getSignal(id) || !c.actions.addSignal({ id, name: id, type: 'bus', role: 'internal', width: 8, displayFormat: 'hex', values: [{ start: 0, value: '00' }] })) throw new Error('could not create arbitrary bus fixture');
  const signal = () => c.selectors.getSignal(id);
  const before = { value: signal().values[0].value, history: c.model.history.undo.length, dirty: c.model.persistence.dirty, document: JSON.stringify(c.getSerializableDocument()) };
  const invalid = c.actions.updateSignalValue(id, 0, 'value', '0x1FF');
  const afterInvalid = { value: signal().values[0].value, history: c.model.history.undo.length, dirty: c.model.persistence.dirty, document: JSON.stringify(c.getSerializableDocument()), validation: c.model.validation };
  const valid = c.actions.updateSignalValue(id, 0, 'value', '0x9A');
  const afterValid = { value: signal().values[0].value, history: c.model.history.undo.length, dirty: c.model.persistence.dirty };
  const saved = c.prepareSaveText();
  await c.actions.openText(saved.text, { fileName: 'issue101.tcd', unsavedDecision: 'discard' });
  const roundTrip = c.selectors.getSignal(id).values[0].value;
  const problemDoc = structuredClone(c.model.document);
  problemDoc.signals.find(item => item.id === id).values[0].value = '1FF';
  const problems = c.getProblems(problemDoc).filter(issue => issue.code === 'bus-width-overflow');
  return { invalid, before, afterInvalid, valid, afterValid, roundTrip, problems: problems.length, parser: c.parseSignalLiteral('1FF', signal()) };
});
assert.equal(result.invalid, false);
assert.equal(result.afterInvalid.value, result.before.value);
assert.equal(result.afterInvalid.history, result.before.history);
assert.equal(result.afterInvalid.dirty, result.before.dirty);
assert.equal(result.afterInvalid.document, result.before.document);
assert.equal(result.afterInvalid.validation[0].code, 'bus-width-overflow');
assert.equal(result.valid, true);
assert.equal(result.afterValid.value, '0x9A');
assert.equal(result.roundTrip, '0x9A');
assert.equal(result.problems, 1);
assert.equal(result.parser.valid, false);
assert.equal(errors.length, 0, errors.join('\n'));
await page.screenshot({ path: path.join(out, 'issue101-1672x941.png') });
await browser.close();
await fs.writeFile(path.join(out, 'acceptance.json'), `${JSON.stringify({ issue: 101, parserCases: true, liveEditorRejectsOverflow: true, problemsUsesSameParser: true, invalidEditAtomic: true, validSaveOpen: true, arbitrarySignalId: true, errors, pass: true }, null, 2)}\n`);
console.log('Issue #101 acceptance passed: shared Bus literal parsing, exact width checks, atomic live edits, Problems consistency, and Save/Open round-trip.');
