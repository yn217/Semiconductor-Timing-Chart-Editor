import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { chromium } from 'playwright';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const out = path.join(root, 'artifacts', 'issue73');
await fs.mkdir(out, { recursive: true });
const browser = await chromium.launch({ headless: true });
const page = await browser.newPage({ viewport: { width: 1672, height: 941 }, deviceScaleFactor: 1 });
const errors = [];
page.on('pageerror', error => errors.push(error.stack || error.message));
await page.goto(`file://${path.join(root, 'gui-mockup', 'index.html').replaceAll('\\', '/')}`);
await page.waitForFunction(() => document.querySelector('#leftPanel .search-row .iconbtn')?.dataset.issue73Bound === 'true');

const controller = () => page.evaluate(() => window.TimingChartProductionController);
const filterButton = page.locator('#leftPanel .search-row .iconbtn');
await filterButton.click();
assert.equal(await page.locator('[data-left-filter-popup]').count(), 1);
await page.locator('[data-left-filter-popup] [data-filter-role="output"]').check();
await page.waitForTimeout(40);
const outputRows = await page.locator('#groups .row[data-signal]:not([hidden])').evaluateAll(rows => rows.map(row => row.dataset.signal));
const outputExpected = await page.evaluate(() => window.TimingChartProductionController.model.document.signals.filter(signal => signal.role === 'output').map(signal => signal.id));
assert.deepEqual(outputRows.sort(), outputExpected.sort());
await page.locator('[data-left-filter-popup] [data-filter-type="bus"]').check();
await page.waitForTimeout(40);
const outputBusRows = await page.locator('#groups .row[data-signal]:not([hidden])').evaluateAll(rows => rows.map(row => row.dataset.signal));
const outputBusExpected = await page.evaluate(() => window.TimingChartProductionController.model.document.signals.filter(signal => signal.role === 'output' && signal.type === 'bus').map(signal => signal.id));
assert.deepEqual(outputBusRows.sort(), outputBusExpected.sort());
await page.locator('[data-left-filter-popup] [data-filter-clear]').click();
assert.equal(await page.evaluate(() => JSON.stringify(window.TimingChartProductionController.model.view.leftFilter)), JSON.stringify({ roles: [], types: [], visibility: 'all' }));
await page.locator('#leftPanel .search').fill('req');
await page.waitForTimeout(20);
const searchRows = await page.locator('#groups .row[data-signal]:not([hidden])').evaluateAll(rows => rows.map(row => row.dataset.signal));
assert.ok(searchRows.includes('req_valid'));
await page.locator('#leftPanel .search').fill('');

const target = page.locator('#groups .row[data-signal="req_addr[7:0]"]');
await target.click();
const targetEye = target.locator('.eye');
const before = await page.evaluate(() => ({ undo: window.TimingChartProductionController.model.history.undo.length, dirty: window.TimingChartProductionController.model.persistence.dirty }));
await targetEye.click();
await page.waitForTimeout(60);
const hidden = await page.evaluate(() => { const c = window.TimingChartProductionController; const signal = c.model.document.signals.find(item => item.id === 'req_addr[7:0]'); return { visible: signal.display?.visible, leftHidden: document.querySelector('#groups .row[data-signal="req_addr[7:0]"]').hidden, timingHidden: document.querySelector('#cycleCanvas .wave-row[data-signal="req_addr[7:0]"]')?.hidden, eye: document.querySelector('#groups .row[data-signal="req_addr[7:0]"] .eye use')?.getAttribute('href'), selection: c.model.selection.id, undo: c.model.history.undo.length, dirty: c.model.persistence.dirty }; });
assert.equal(hidden.visible, false);
assert.equal(hidden.leftHidden, false);
assert.equal(hidden.timingHidden, true);
assert.equal(hidden.eye, 'icons.svg#i-eye-off');
assert.equal(hidden.selection, 'req_addr[7:0]');
assert.equal(hidden.undo - before.undo, 1);
assert.equal(hidden.dirty, true);
await page.evaluate(() => window.TimingChartProductionController.actions.undo());
await page.waitForTimeout(40);
assert.equal(await page.evaluate(() => window.TimingChartProductionController.model.document.signals.find(item => item.id === 'req_addr[7:0]').display?.visible), undefined);
await page.evaluate(() => window.TimingChartProductionController.actions.redo());
await page.waitForTimeout(40);
assert.equal(await page.evaluate(() => window.TimingChartProductionController.model.document.signals.find(item => item.id === 'req_addr[7:0]').display?.visible), false);

const saved = await page.evaluate(() => window.TimingChartProductionController.prepareSaveText().text);
const savedJson = JSON.parse(saved);
assert.equal(savedJson.signals.find(signal => signal.id === 'req_addr[7:0]').display.visible, false);
assert.equal('leftFilter' in savedJson, false);
assert.equal(await page.evaluate(async text => window.TimingChartProductionController.actions.openText(text, { fileName: 'issue73-hidden.tcd', unsavedDecision: 'discard' }), saved), true);
assert.equal(await page.evaluate(() => window.TimingChartProductionController.model.document.signals.find(item => item.id === 'req_addr[7:0]').display.visible), false);

const commentId = await page.locator('#groups .row[data-kind="comment"]').first().getAttribute('data-signal');
const commentRow = page.locator(`#groups .row[data-signal="${commentId}"]`);
await commentRow.locator('.eye').click();
await page.waitForTimeout(40);
assert.equal(await page.evaluate(id => window.TimingChartProductionController.model.document.signals.find(item => item.id === id).display.visible, commentId), false);
assert.equal(await commentRow.isHidden(), false);
assert.equal(await page.evaluate(id => [...document.querySelectorAll('#cycleCanvas .wave-row')].find(row => row.dataset.signal === id)?.hidden, commentId), true);
const commentSaved = JSON.parse(await page.evaluate(() => window.TimingChartProductionController.prepareSaveText().text));
assert.equal(commentSaved.signals.find(signal => signal.id === commentId).display.visible, false);
await commentRow.locator('.eye').click();
await page.waitForTimeout(40);

await page.evaluate(() => window.TimingChartProductionController.actions.setLeftPanelMode('hierarchy'));
await page.waitForTimeout(60);
assert.equal(await page.evaluate(() => window.TimingChartProductionController.model.document.signals.find(item => item.id === 'req_addr[7:0]').display.visible), false);
const hierarchyEye = page.locator('#groups .row[data-signal="req_addr[7:0]"] .eye');
assert.equal(await hierarchyEye.locator('use').getAttribute('href'), 'icons.svg#i-eye-off');
await page.evaluate(() => window.TimingChartProductionController.actions.setLeftPanelMode('group'));

await page.locator('#leftPanel .panel-head .iconbtn').click();
assert.equal(await page.locator('[data-left-overflow-popup]').count(), 1);
await page.locator('[data-left-overflow-popup] [data-left-overflow="full-path"]').click();
assert.equal(await page.evaluate(() => window.TimingChartProductionController.model.document.layout.pathDisplayMode), 'full');
await page.locator('#leftPanel .panel-head .iconbtn').click();
await page.locator('[data-left-overflow-popup] [data-left-overflow="hierarchy-view"]').click();
assert.equal(await page.evaluate(() => window.TimingChartProductionController.model.view.leftPanelMode), 'hierarchy');
await page.evaluate(() => window.TimingChartProductionController.actions.setLeftPanelMode('group'));

await page.screenshot({ path: path.join(out, 'issue73-1672x941.png') });
await browser.close();
assert.equal(errors.length, 0, errors.join('\n'));
await fs.writeFile(path.join(out, 'acceptance.json'), `${JSON.stringify({ issue: 73, filter: { outputRows, outputExpected, outputBusRows, outputBusExpected }, hidden, savedVisibility: savedJson.signals.find(signal => signal.id === 'req_addr[7:0]').display.visible, errors, pass: true }, null, 2)}\n`);
console.log('Issue #73 acceptance passed: canonical filter, persisted visibility, hierarchy synchronization, and overflow/add controls.');
