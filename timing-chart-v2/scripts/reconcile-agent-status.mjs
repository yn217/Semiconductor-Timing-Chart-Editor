import fs from 'node:fs/promises';
import path from 'node:path';
import process from 'node:process';
import { execFileSync } from 'node:child_process';

const root = process.cwd();
const planPath = path.join(root, '.agents', 'PLAN.yaml');
const generatedAt = new Date().toISOString();
const priorityRank = { P0: 0, P1: 1, P2: 2, P3: 3 };
const owners = new Set(['codex', 'claude', 'shared', 'hold']);
function gitSha(ref) {
  try { return execFileSync('git', ['rev-parse', ref], { cwd: root, encoding: 'utf8' }).trim(); } catch { return 'unknown'; }
}

function scalar(value) {
  const v = value.trim();
  if (!v) return '';
  if (v === '[]') return [];
  if (/^\[.*\]$/.test(v)) return v.slice(1, -1).split(',').map(x => x.trim()).filter(Boolean).map(Number);
  if (/^\d+$/.test(v)) return Number(v);
  return v.replace(/^['"]|['"]$/g, '');
}

function parsePlan(text) {
  const result = { version: 1, issues: {} };
  let current = null;
  for (const raw of text.split(/\r?\n/)) {
    const line = raw.replace(/#.*$/, '').trimEnd();
    if (!line.trim() || line.trim() === 'issues:' || line.trim() === 'version: 1') continue;
    const issue = line.match(/^  (\d+):\s*$/);
    if (issue) { current = issue[1]; result.issues[current] = {}; continue; }
    const field = line.match(/^    ([A-Za-z][A-Za-z0-9]*):\s*(.*)$/);
    if (field && current) result.issues[current][field[1]] = scalar(field[2]);
  }
  return result;
}

async function githubIssues() {
  let token = process.env.GITHUB_TOKEN || process.env.GH_TOKEN;
  if (!token) {
    try { token = execFileSync('gh', ['auth', 'token'], { encoding: 'utf8' }).trim(); } catch { /* CI may provide an anonymous tokenless run */ }
  }
  const repo = process.env.GITHUB_REPOSITORY || 'yn217/Semiconductor-Timing-Chart-Editor';
  const headers = { Accept: 'application/vnd.github+json', 'X-GitHub-Api-Version': '2022-11-28' };
  if (token) headers.Authorization = `Bearer ${token}`;
  const issues = [];
  for (let page = 1; ; page++) {
    const response = await fetch(`https://api.github.com/repos/${repo}/issues?state=all&per_page=100&page=${page}`, { headers });
    if (!response.ok) throw new Error(`GitHub API ${response.status}: ${await response.text()}`);
    const batch = await response.json();
    issues.push(...batch.filter(item => !item.pull_request));
    if (batch.length < 100) return { repo, issues, requestCount: page };
  }
}

function validate(plan) {
  const errors = [];
  const seenOwners = new Map();
  for (const [number, entry] of Object.entries(plan.issues)) {
    if (!owners.has(entry.owner)) errors.push(`#${number}: invalid owner '${entry.owner || ''}'`);
    if (!(entry.priority in priorityRank)) errors.push(`#${number}: invalid priority '${entry.priority || ''}'`);
    for (const dep of entry.dependsOn || []) {
      if (String(dep) === number) errors.push(`#${number}: self dependency`);
      if (!plan.issues[String(dep)]) errors.push(`#${number}: missing PLAN dependency #${dep}`);
    }
    if (entry.owner && entry.owner !== 'hold') {
      if (seenOwners.has(number)) errors.push(`#${number}: duplicate owner`);
      seenOwners.set(number, entry.owner);
    }
  }
  const visiting = new Set(), visited = new Set();
  const walk = n => { if (visiting.has(n)) errors.push(`dependency cycle at #${n}`); if (visited.has(n)) return; visiting.add(n); for (const d of plan.issues[n]?.dependsOn || []) walk(String(d)); visiting.delete(n); visited.add(n); };
  for (const n of Object.keys(plan.issues)) walk(n);
  if (errors.length) throw new Error(`PLAN validation failed:\n${errors.join('\n')}`);
}

function renderQueue(status) {
  const lines = ['# Generated by scripts/reconcile-agent-status.mjs', '# Non-comment lines are executable Codex queue entries.', 'AUTOGENERATED STATUS'];
  for (const n of status.codex.ready) lines.push(`#${n}`);
  lines.push('END AUTOGENERATED STATUS', '', 'STATIC EXECUTION POLICY', 'Read the current main worktree before editing.', 'Do not execute blocked or closed issues.', 'Preserve canonical -> semantic commands -> projection -> renderer boundaries.');
  return `${lines.join('\n')}\n`;
}

function renderAssignment(status, sha, control) {
  const rows = owner => status[owner].ready.length ? status[owner].ready.map(n => `- #${n}`).join('\n') : '- none';
  const blocked = Object.entries(status.issues).filter(([, x]) => x.blocked).map(([n, x]) => `- #${n}: #${x.blockedBy.join(', #')}`).join('\n') || '- none';
  return `# Agent Assignment\n\nGenerated: ${status.generatedAt}\nMain: ${sha}\nCodex control: ${control}\n\n## Codex ready\n${rows('codex')}\n\n## Claude ready\n${rows('claude')}\n\n## Blocked dependencies\n${blocked}\n\n## Ownership rules\n- One active implementation owner per Issue.\n- GitHub state is authoritative; Issue progress prose is not parsed.\n- Codex implementation changes target main; control artifacts are generated separately.\n`;
}

function renderProject(status, sha) {
  const table = owner => status[owner].ready.length ? status[owner].ready.map(n => `| ${status.issues[n].priority} | #${n} | ready | - |`).join('\n') : '| - | - | none | - |';
  const blocked = Object.entries(status.issues).filter(([, x]) => x.blocked).map(([n, x]) => `#${n} -> #${x.blockedBy.join(', #')}`).join('\n') || 'none';
  const completed = Object.entries(status.issues).filter(([, x]) => x.state === 'closed').map(([n]) => `#${n}`).slice(0, 10).join(', ') || 'none';
  return `# Project Status\n\nGenerated: ${status.generatedAt}\nMain: ${sha}\n\n## Codex\n| Priority | Issue | Status | Blocked by |\n|---|---|---|---|\n${table('codex')}\n\n## Claude\n| Priority | Issue | Status | Blocked by |\n|---|---|---|---|\n${table('claude')}\n\n## Dependency chain\n${blocked}\n\n## Recently completed\n${completed}\n`;
}

const startedAt = Date.now();
const plan = parsePlan(await fs.readFile(planPath, 'utf8'));
validate(plan);
const live = await githubIssues();
const byNumber = new Map(live.issues.map(x => [String(x.number), x]));
const status = { generatedAt, main: process.env.GIT_SHA || gitSha('HEAD'), codexControl: process.env.CODEX_CONTROL_SHA || gitSha('origin/codex-control'), codex: { ready: [], blocked: [], completed: [] }, claude: { ready: [], blocked: [], completed: [] }, issues: {} };
for (const [number, planEntry] of Object.entries(plan.issues)) {
  const liveIssue = byNumber.get(number);
  if (!liveIssue) throw new Error(`PLAN issue #${number} does not exist on GitHub`);
  const deps = (planEntry.dependsOn || []).map(String);
  const blockedBy = deps.filter(dep => byNumber.get(dep)?.state !== 'closed');
  const item = { state: liveIssue.state, title: liveIssue.title, updatedAt: liveIssue.updated_at, owner: planEntry.owner, priority: planEntry.priority, area: planEntry.area, blocked: liveIssue.state === 'open' && blockedBy.length > 0, blockedBy, stalePlanEntry: false };
  status.issues[number] = item;
  const bucket = status[planEntry.owner] || status.codex;
  if (liveIssue.state === 'closed') bucket.completed.push(Number(number));
  else if (item.blocked || planEntry.owner === 'hold' || planEntry.hold) bucket.blocked.push(Number(number));
  else if (planEntry.owner === 'codex' || planEntry.owner === 'claude') bucket.ready.push(Number(number));
}
for (const owner of ['codex', 'claude']) {
  status[owner].ready.sort((a,b) => priorityRank[status.issues[a].priority] - priorityRank[status.issues[b].priority] || (plan.issues[a].order ?? 9999) - (plan.issues[b].order ?? 9999) || a-b);
  status[owner].blocked.sort((a,b) => a-b); status[owner].completed.sort((a,b) => a-b);
}
const sha = status.main;
const control = status.codexControl;
await fs.mkdir(path.join(root, '.agents'), { recursive: true });
await fs.writeFile(path.join(root, '.agents', 'STATUS.json'), `${JSON.stringify({ ...status, metrics: { issueCount: live.issues.length, githubRequestCount: live.requestCount, elapsedMs: Date.now() - startedAt } }, null, 2)}\n`);
await fs.mkdir(path.join(root, '.codex'), { recursive: true });
await fs.writeFile(path.join(root, '.codex', 'ISSUE_ORDER.txt'), renderQueue(status));
await fs.writeFile(path.join(root, '.codex', 'AGENT_ASSIGNMENT.md'), renderAssignment(status, sha, control));
await fs.mkdir(path.join(root, 'docs'), { recursive: true });
await fs.writeFile(path.join(root, 'docs', 'PROJECT_STATUS.md'), renderProject(status, sha));
console.log(JSON.stringify({ generatedAt, repo: live.repo, issueCount: live.issues.length, githubRequestCount: live.requestCount, elapsedMs: Date.now() - startedAt, codexReady: status.codex.ready, claudeReady: status.claude.ready }, null, 2));
