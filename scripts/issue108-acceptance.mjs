import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { chromium } from 'playwright';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const out = path.join(root, 'artifacts', 'issue108');
await fs.mkdir(out, { recursive: true });
const browser = await chromium.launch({ headless: true });
const page = await browser.newPage({ viewport: { width: 1672, height: 941 }, deviceScaleFactor: 1 });
const errors = [];
page.on('pageerror', error => errors.push(error.stack || error.message));
await page.goto(`file://${path.join(root, 'gui-mockup', 'index.html').replaceAll('\\', '/')}`);
await page.waitForTimeout(350);

const result = await page.evaluate(async () => {
  const c = window.TimingChartProductionController;
  const add = (start, name, comment = '') => c.actions.addBookmark(start, { name, comment });
  const baselineSelection = structuredClone(c.model.selection);
  const initialHidden = document.querySelector('#bottomTabs [data-tab="bookmarks"]')?.hidden === true;
  add(1, 'Address accepted', 'AWVALID && AWREADY');
  add(7, 'First response', 'BVALID first edge');
  add(7, 'Same-time second', 'second bookmark');
  const ids = c.model.document.bookmarks.map(item => item.id);
  const firstId = ids.find(id => c.model.document.bookmarks.find(item => item.id === id)?.name === 'First response');
  const edited = c.actions.updateBookmark(firstId, 'name', 'Renamed response') && c.actions.updateBookmark(firstId, 'comment', 'edited comment');
  const beforeJumpRender = c.timeAxisMetrics.waveDromRenders;
  const beforeJump = c.model.persistence.dirty;
  const jumped = c.actions.revealBookmark(firstId);
  const afterJumpRender = c.timeAxisMetrics.waveDromRenders;
  const jumpState = { cycle: c.model.timeSelection.cycle, selected: c.model.selection.id, tab: c.model.view.tab, dirty: c.model.persistence.dirty, renderDelta: afterJumpRender - beforeJumpRender };
  const saved = c.prepareSaveText();
  const opened = await c.actions.openText(saved.text, { fileName: 'issue108-roundtrip.tcd', unsavedDecision: 'discard' });
  const roundTrip = structuredClone(c.model.document.bookmarks);
  const bulkWaveBefore = c.timeAxisMetrics.waveDromRenders;
  for (let index = 0; index < 100; index += 1) add(7, `Bulk ${index}`);
  const bulkWaveDelta = c.timeAxisMetrics.waveDromRenders - bulkWaveBefore;
  const beforeInsert = c.model.document.bookmarks.map(item => item.start);
  const inserted = c.actions.insertCycles(5, 5);
  const afterInsert = c.model.document.bookmarks.map(item => item.start);
  const undone = c.actions.undo();
  const restored = c.model.document.bookmarks.map(item => item.start);
  return { baselineSelection, initialHidden, ids, edited, jumped, jumpState, beforeJump, opened, roundTrip, bulkCount: c.model.document.bookmarks.length, bulkWaveDelta, beforeInsert, inserted, afterInsert, undone, restored, metrics: c.timeAxisMetrics, bookmarksTabHidden: document.querySelector('#bottomTabs [data-tab="bookmarks"]')?.hidden, validation: c.model.validation };
});

assert.equal(result.edited, true);
assert.equal(result.initialHidden, true);
assert.equal(result.jumped, true);
assert.equal(result.jumpState.cycle, 7);
assert.equal(result.jumpState.selected, result.ids.find(id => result.roundTrip.find(item => item.id === id)?.name === 'Renamed response') || result.jumpState.selected);
assert.equal(result.jumpState.tab, 'bookmarks');
assert.equal(result.jumpState.dirty, true);
assert.equal(result.jumpState.renderDelta, 0);
assert.equal(result.opened, true);
assert.equal(result.bulkCount, 103);
assert.equal(result.bulkWaveDelta, 0);
assert.ok(result.roundTrip.some(item => item.name === 'Renamed response' && item.comment === 'edited comment'));
assert.deepEqual(result.afterInsert, result.beforeInsert.map(value => value >= 5 ? value + 5 : value));
assert.equal(result.undone, true);
assert.deepEqual(result.restored, result.beforeInsert);
assert.equal(result.validation.length, 0);
assert.equal(result.errors?.length || 0, 0);
await page.screenshot({ path: path.join(out, 'issue108-1672x941.png') });
await browser.close();
const acceptance = { issue: 108, lifecycle: true, sameTimeStableIds: result.ids.length === new Set(result.ids).size, jump: result.jumpState, saveOpen: result.opened, insertUndo: result.afterInsert, artifacts: ['issue108-1672x941.png'], errors, pass: true };
await fs.writeFile(path.join(out, 'acceptance.json'), `${JSON.stringify(acceptance, null, 2)}\n`);
console.log('Issue #108 acceptance passed: bookmark lifecycle, jump, persistence, and timeline insert/undo.');
