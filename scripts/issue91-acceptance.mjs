  const afterCancel=JSON.stringify(c.getSerializableDocument());
  const discarded=await c.actions.openSample('02_ahb_lite_pipelined_transfer.tcd.json',{unsavedDecision:'discard'});
  const ahbLoaded={fileName:c.model.persistence.fileName,source:c.model.persistence.source,signalIds:c.model.document.signals.map(signal=>signal.id),dirty:c.model.persistence.dirty};
  let openOptions=null;
  window.showOpenFilePicker=async options=>{openOptions=options;return [{getFile:async()=>new File([apb],'01_apb_register_access.tcd.json',{type:'application/json'})}];};
  const nativeOpen=await c.actions.requestOpen({unsavedDecision:'discard'});
  const nativeExtensions=openOptions?.types?.[0]?.accept?.['application/json']||[];
  window.showOpenFilePicker=undefined;
  const fallbackPending=c.actions.requestOpen({unsavedDecision:'discard'}); await Promise.resolve();
  const fallbackInput=document.querySelector('input[data-open-fallback]'); const fallbackAccept=fallbackInput?.accept||''; fallbackInput?.dispatchEvent(new Event('cancel')); const fallbackResult=await fallbackPending;
  await c.actions.openSample('01_apb_register_access.tcd.json',{unsavedDecision:'discard'});
  c.actions.updateSignalValue(c.model.document.signals.find(signal=>signal.type==='binary')?.id,0,'value','1');
  let saveCalls=0,writes=0,lastText='';
  window.showSaveFilePicker=async options=>{saveCalls+=1;return {createWritable:async()=>({write:async text=>{writes+=1;lastText=text;},close:async()=>{}})};};
  const sampleBeforeSave=c.model.persistence.source;
  const firstSave=await c.actions.save();
  const afterSave={source:c.model.persistence.source,saveCalls,writes,fileName:c.model.persistence.fileName,hasFormat2:JSON.parse(lastText).formatVersion===2};
  c.actions.updateSignalValue(c.model.document.signals.find(signal=>signal.type==='binary')?.id,0,'value','0');
  const secondSave=await c.actions.save();
  const afterSecondSave={secondSave,saveCalls,writes,source:c.model.persistence.source};
  await c.actions.openSample('01_apb_register_access.tcd.json',{unsavedDecision:'discard'});
