import assert from 'node:assert/strict';
import fs from 'node:fs';
import { spawn } from 'node:child_process';
import { chromium } from 'playwright';

const server = spawn('python', ['-m', 'http.server', '4176'], { cwd: process.cwd(), stdio: 'ignore' });
const wait = ms => new Promise(resolve => setTimeout(resolve, ms));
try {
  await wait(700);
  const browser = await chromium.launch({ headless: true });
  const page = await browser.newPage({ viewport: { width: 1672, height: 941 }, deviceScaleFactor: 1 });
  await page.goto('http://127.0.0.1:4176/gui-mockup/', { waitUntil: 'networkidle' });
  assert.equal(await page.locator('script[src="app.js"],script[src="ui-golden-v3.js"]').count(), 0, 'Legacy Production logic script is loaded');
  assert.equal(await page.locator('script[src="production-controller.js"]').count(), 1, 'Phase 3A controller is not loaded');
  assert.ok(await page.evaluate(() => Boolean(window.TimingChartProductionController)), 'Phase 3A controller is unavailable');
  await page.screenshot({ path: 'test-results/phase3a-production.png' });
  assert.equal(await page.locator('.ribbon-tabs .cycle-only:visible').count(), 1);
  assert.equal(await page.locator('.ribbon-tabs .txn-only:visible').count(), 0);
  await page.locator('[data-mode="transaction"]').click();
  assert.equal(await page.locator('#transactionCanvas:not(.hidden)').count(), 1);
  assert.equal(await page.locator('[data-tab="transaction"]:visible').count(), 1);
  assert.equal(await page.locator('[data-tab="signal"]:visible').count(), 0);
  assert.equal(await page.locator('.ribbon-tabs .cycle-only:visible').count(), 0);
  assert.equal(await page.locator('.ribbon-tabs .txn-only:visible').count(), 1);
  await page.screenshot({ path: 'test-results/phase3a-transaction.png' });
  await page.locator('[data-mode="split"]').click();
  assert.equal(await page.locator('[data-tab="signal"]:visible').count(), 1);
  assert.equal(await page.locator('[data-tab="transaction"]:visible').count(), 1);
  assert.equal(await page.locator('[data-tab="annotation"]:visible').count(), 1);
  await page.screenshot({ path: 'test-results/phase3a-split.png' });
  await page.locator('[data-mode="cycle"]').click();
  assert.equal(await page.locator('#transactionCanvas:not(.hidden)').count(), 0);
  assert.equal(await page.locator('[data-tab="transaction"]:visible').count(), 0);
  await page.locator('[data-signal="clk"]').click();
  let state = await page.evaluate(() => window.TimingChartProductionController.getState());
  assert.deepEqual(state.selection, { kind: 'signal', id: 'clk' });
  assert.equal(state.view.tab, 'signal');
  assert.equal(await page.locator('[data-signal="clk"].selected').count(), 1);
  await page.locator('[data-signal="Address phase"]').click();
  state = await page.evaluate(() => window.TimingChartProductionController.getState());
  assert.deepEqual(state.selection, { kind: 'comment', id: 'Address phase' });
  assert.equal(await page.locator('[data-signal="Address phase"].selected').count(), 1);
  await page.locator('[data-tab="annotation"]').click();
  state = await page.evaluate(() => window.TimingChartProductionController.getState());
  assert.equal(state.view.tab, 'annotation');
  await page.locator('#bottomTabs input[type="checkbox"]').uncheck();
  await page.locator('[data-signal="req_valid"]').click();
  state = await page.evaluate(() => window.TimingChartProductionController.getState());
  assert.deepEqual(state.selection, { kind: 'signal', id: 'req_valid' });
  assert.equal(state.view.tab, 'annotation', 'Follow Selection OFF did not pin tab');
  await page.locator('#bottomTabs .follow button').click();
  assert.equal((await page.evaluate(() => window.TimingChartProductionController.getState())).view.pinned, true);
  assert.equal((await page.evaluate(() => window.TimingChartProductionController.getState())).view.followSelection, false);
  state = await page.evaluate(() => window.TimingChartProductionController.getState());
  fs.mkdirSync('test-results', { recursive: true });
  fs.writeFileSync('test-results/phase3a-state.json', JSON.stringify(state, null, 2));
  await browser.close();
  console.log('Phase 3A acceptance passed: view mode, selection, bottom tabs, follow selection, pin, DOM lock, and legacy script exclusion.');
} finally { server.kill(); }
