import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { chromium } from 'playwright';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const out = path.join(root, 'artifacts', 'issue57');
await fs.mkdir(out, { recursive: true });
const controllerSource = await fs.readFile(path.join(root, 'gui-mockup', 'production-controller.js'), 'utf8');
const zoomSource = await fs.readFile(path.join(root, 'gui-mockup', 'zoom-fix.js'), 'utf8');
const selectionSource = await fs.readFile(path.join(root, 'gui-mockup', 'selection-performance-fix.js'), 'utf8');
const viewSource = await fs.readFile(path.join(root, 'gui-mockup', 'view-ribbon.js'), 'utf8');
const annotationSource = await fs.readFile(path.join(root, 'gui-mockup', 'annotation-ribbon.js'), 'utf8');
const indexSource = await fs.readFile(path.join(root, 'gui-mockup', 'index.html'), 'utf8');
assert.equal((controllerSource.match(/actions\.setZoom\s*=/g) || []).length, 0, 'setZoom remains duplicated in controller');
assert.equal((controllerSource.match(/actions\.fit(All|Selection)\s*=/g) || []).length, 0, 'fit action remains duplicated in controller');
assert.equal((controllerSource.match(/actions\.selectObject\s*=/g) || []).length, 0, 'selectObject remains duplicated in controller');
assert.equal((zoomSource.match(/actions\.setZoom\s*=/g) || []).length, 1, 'setZoom must have one owner');
assert.equal((zoomSource.match(/actions\.fit(All|Selection)\s*=/g) || []).length, 2, 'fit actions must have one owner');
assert.equal((selectionSource.match(/actions\.selectObject\s*=/g) || []).length, 1, 'selectObject must have one owner');
assert.equal(/document\.createElement\('script'\)/.test(zoomSource), false, 'zoom module dynamically injects scripts');
assert.equal(/controller\.render\s*=/.test(viewSource), false, 'view ribbon still monkey-patches render');
assert.equal(/actions\.selectAnnotation\s*=/.test(annotationSource), false, 'annotation ribbon still monkey-patches selectAnnotation');
assert.equal((indexSource.match(/selection-performance-fix\.js/g) || []).length, 1, 'selection fast path is not explicitly loaded exactly once');

const browser = await chromium.launch({ headless: true });
const page = await browser.newPage({ viewport: { width: 1672, height: 941 }, deviceScaleFactor: 1 });
const errors = [];
page.on('pageerror', error => errors.push(error.message));
await page.goto(`file://${path.join(root, 'gui-mockup', 'index.html').replaceAll('\\', '/')}`);
await page.waitForTimeout(350);
const result = await page.evaluate(async () => {
  const c = window.TimingChartProductionController;
  const wait = ms => new Promise(resolve => setTimeout(resolve, ms));
  const before = JSON.stringify(c.getSerializableDocument());
  const hookNames = [...c.renderHooks.after.keys()];
  const scripts = [...document.scripts].map(script => script.src).filter(Boolean);
  const row = document.querySelector('.row[data-signal="req_valid"]');
  row?.click(); await wait(40);
  const selected = c.model.selection.id === 'req_valid' && c.selectionMetrics.selections >= 1;
  const zoomBefore = c.model.view.zoom; c.actions.setZoom(125); await wait(40);
  const zoomed = c.model.view.zoom === 1.25 && c.zoomMetrics.requests >= 1;
  const annotation = c.model.document.annotations?.[0];
  const selectedAnnotation = annotation && c.actions.selectAnnotation(annotation.id); await wait(30);
  const annotationHook = hookNames.includes('annotation-ribbon') && document.querySelector('#ribbonAnnotation');
  const viewHook = hookNames.includes('view-ribbon') && c.renderHooks.after.size === new Set(hookNames).size;
  const unchanged = before === JSON.stringify(c.getSerializableDocument());
  return { selected, zoomed, zoomBefore, selectedAnnotation, annotationHook, viewHook, unchanged, hookNames, selectionScriptCount: scripts.filter(src => src.endsWith('/selection-performance-fix.js')).length };
});
const pass = Object.values({ sourceGuards: true, ...result }).every(value => typeof value === 'boolean' ? value : true) && errors.length === 0 && result.selectionScriptCount === 1;
const report = { issue: 57, result, errors, pass, sourceGuards: { explicitSelectionScript: true, noDynamicScriptInjection: true, singleZoomOwner: true, singleSelectionOwner: true, renderHooks: true }, artifacts: ['issue57-1672x941.png'] };
await page.screenshot({ path: path.join(out, 'issue57-1672x941.png') });
await browser.close();
await fs.writeFile(path.join(out, 'acceptance.json'), `${JSON.stringify(report, null, 2)}\n`);
assert.ok(pass, JSON.stringify(report, null, 2));
console.log('Issue #57 acceptance passed: deterministic action ownership and render hooks verified.');
